/**
 * One-off — add the client-account LINKAGE columns:
 *
 *   Lead Board:     Client Account Id  [text]  (+ Previous Case Ref [text] for
 *                   the Phase-4 "new application" reuse seam)
 *   Client Master:  Client Account Id  [text]  — the functional key
 *                   Client             [board_relation → Clients] — navigation,
 *                                        best-effort
 *
 * Lead column ids merge into src/data/newLeadsBoard.json (standard pattern);
 * the Client Master ids are persisted into src/data/clientsBoard.json under
 * `cmLinkColumns` (that file is generated by create-clients-board.js and is
 * the single config clientAccountService loads). Run create-clients-board.js
 * --write FIRST — the CM board_relation needs the Clients board id.
 *
 * All columns are INERT until config/features.js flags turn stamping on.
 *
 *   node scripts/add-client-account-columns.js            # dry-run
 *   node scripts/add-client-account-columns.js --write    # create missing
 */

'use strict';

require('dotenv').config();
const fs        = require('fs');
const path      = require('path');
const mondayApi = require('../src/services/mondayApi');

const WRITE         = process.argv.includes('--write');
const LEAD_BOARD_ID = process.env.MONDAY_LEAD_BOARD_ID || '18416845157';
const CM_BOARD_ID   = process.env.MONDAY_CLIENT_MASTER_BOARD_ID || '18401523447';
const LEADS_PATH    = path.join(__dirname, '..', 'src', 'data', 'newLeadsBoard.json');
const CLIENTS_PATH  = path.join(__dirname, '..', 'src', 'data', 'clientsBoard.json');

const LEAD_COLS = [
  { key: 'clientAccountId', title: 'Client Account Id', type: 'text' },
  { key: 'previousCaseRef', title: 'Previous Case Ref', type: 'text' },
];

async function createColumn(boardId, title, type, defaults) {
  const data = await mondayApi.query(
    `mutation($boardId: ID!, $title: String!, $type: ColumnType!, $defaults: JSON) {
       create_column(board_id: $boardId, title: $title, column_type: $type, defaults: $defaults) { id title type }
     }`,
    { boardId: String(boardId), title, type, defaults: defaults ? JSON.stringify(defaults) : null }
  );
  console.log(`   + ${title.padEnd(20)} [${type}] → ${data.create_column.id}`);
  return data.create_column.id;
}

async function main() {
  console.log(`Mode: ${WRITE ? '✏  WRITE' : '🔍 DRY-RUN'}  |  lead board ${LEAD_BOARD_ID}, CM ${CM_BOARD_ID}`);

  const leadsCfg = JSON.parse(fs.readFileSync(LEADS_PATH, 'utf8'));
  const clientsCfg = fs.existsSync(CLIENTS_PATH) ? JSON.parse(fs.readFileSync(CLIENTS_PATH, 'utf8')) : null;
  if (!clientsCfg) {
    console.log('⚠ src/data/clientsBoard.json missing — run create-clients-board.js --write first.');
    if (WRITE) process.exit(1);
  }
  const cmLink = (clientsCfg && clientsCfg.cmLinkColumns) || {};

  const leadTodo = LEAD_COLS.filter((c) => !(leadsCfg.columns || {})[c.key]);
  const cmTodo = [];
  if (!cmLink.clientAccountId) cmTodo.push({ key: 'clientAccountId', title: 'Client Account Id', type: 'text' });
  if (!cmLink.clientRelation)  cmTodo.push({ key: 'clientRelation', title: 'Client', type: 'board_relation' });

  console.log(`Lead board: ${leadTodo.length ? leadTodo.map((c) => c.title).join(', ') : 'nothing to do'}`);
  console.log(`Client Master: ${cmTodo.length ? cmTodo.map((c) => c.title).join(', ') : 'nothing to do'}`);
  if (!WRITE) { console.log('(Dry-run. Re-run with --write to create.)'); return; }

  for (const c of leadTodo) {
    leadsCfg.columns[c.key] = await createColumn(LEAD_BOARD_ID, c.title, c.type);
    await new Promise((r) => setTimeout(r, 200));
  }
  if (leadTodo.length) {
    fs.writeFileSync(LEADS_PATH, `${JSON.stringify(leadsCfg, null, 2)}\n`);
    console.log(`Saved ${path.relative(process.cwd(), LEADS_PATH)}`);
  }

  for (const c of cmTodo) {
    try {
      cmLink[c.key] = await createColumn(
        CM_BOARD_ID, c.title, c.type,
        c.type === 'board_relation' ? { boardIds: [Number(clientsCfg.boardId)] } : null
      );
    } catch (err) {
      if (c.type === 'board_relation') {
        console.warn(`     ⚠ board_relation "Client" failed (${err.message}) — skipping; the text id column is the functional key.`);
        continue;
      }
      throw err;
    }
    await new Promise((r) => setTimeout(r, 200));
  }
  if (cmTodo.length) {
    clientsCfg.cmLinkColumns = cmLink;
    fs.writeFileSync(CLIENTS_PATH, `${JSON.stringify(clientsCfg, null, 2)}\n`);
    console.log(`Saved ${path.relative(process.cwd(), CLIENTS_PATH)}`);
  }
  console.log('Done.');
}

main().catch((err) => { console.error('Fatal:', err); process.exit(1); });
