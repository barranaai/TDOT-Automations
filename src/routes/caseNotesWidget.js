/**
 * Consultation notes panel — on the CASE page, beside every tab (plan case-notes, switch CASE_NOTES_PANEL).
 *
 *   CASE_NOTES_CSS   — the layout (the grid beside the tab panels, the rail, the narrow bar) and the cards (.cnp-*)
 *   caseNotesHtml()  — the panel's STATIC markup: the page's render() / loadCase() never touch it
 *   CASE_NOTES_JS    — defines window.tdotCaseNotesMount({ caseRef }): its own fetch of /admin/case-notes/:caseRef
 *
 * One card per consultation (newest first): when, who, the recording code to type as the Otter title, the
 * Otter recordings the app filed (summary first, the transcript link, a transcript posted as an entry kept
 * folded), then the notes oldest → newest ("Typed by <name>, <date>"), then Add note (Monday sign-in only).
 *
 * Rules kept here on purpose (the same as the record page's box, consultNotesWidget.js):
 *   - every entry is drawn with textContent; innerHTML is never used;
 *   - a draft is kept on this device per consultation under tdot_cnotes_case_<leadId>, in the record page's
 *     per-tab format { who, d: { tab: { t, at, by } } }, so Sign Out (adminShared.js) asks first and clears it;
 *   - ONE beforeunload handler and ONE window.tdotNotesUnsaved for every open box on the page;
 *   - the list is never redrawn while a box holds text; a failed read says so, never an empty list;
 *   - every storage call is in try/catch; the panel works without storage;
 *   - the JS is a plain-string array: no backticks, no backslashes, no dollar-brace (test/inlineScripts.test.js).
 */

