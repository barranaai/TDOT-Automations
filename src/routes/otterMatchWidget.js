/**
 * "Otter recordings to match" — the strip above the tabs of the Consultations page (2026-11-14).
 *
 * A recording the app could not place on a consultation with certainty waits here: staff see
 * when it was made, the title that was typed, the first words of the summary and why it was not
 * placed, choose the client (the best suggestion is already chosen; the search box finds any
 * consultation by name or code) and press "Save to this client" — or "Not a consultation".
 * A row whose file cannot be opened for good (saveable: false) offers ONLY "Not a consultation" —
 * no picker and no Save button that could never work (review 2, 2026-11-14).
 * The strip is shown ONLY when there is something to match and the feature is switched on
 * (GET /api/otter/needs-matching answers { on, items }) — and it STAYS, with its "Saved to …" line,
 * when the last row leaves because of what the staff member just did (review 2026-11-14).
 *
 *   OTTER_MATCH_CSS    — styles (namespaced .om-*), the page's shared colour variables
 *   otterMatchHtml()   — the static shell (hidden until the list has rows)
 *   OTTER_MATCH_JS     — defines tdotOtterMatchMount({ rows, signIn })
 *
 * Rules kept here on purpose:
 *   - everything from the server is put on the page with textContent, never innerHTML;
 *   - the JS is a plain-string array with no backticks, no dollar-brace and no backslashes
 *     (it is interpolated into the page's template literal — see test/inlineScripts.test.js);
 *   - "Not a consultation" asks first, in the shared pop-up (dialogUi.js tdotDialogNew);
 *   - after a save the row leaves the list without a page reload.
 */

