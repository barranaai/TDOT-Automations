const OTTER_MATCH_JS = [
  'function tdotOtterMatchMount(opts){',
  '  opts = opts || {};',
  '  var strip = document.getElementById("om-strip");',
  '  if (!strip) return;',
  '  var listEl = document.getElementById("om-list"), nEl = document.getElementById("om-n"), toggle = document.getElementById("om-toggle");',
  '  var bodyEl = document.getElementById("om-body"), topEl = document.getElementById("om-top");',
  '  var hintEl = document.getElementById("om-hint"), doneEl = document.getElementById("om-done");',
  '  var ITEMS = [];',
  '  var SIGN_IN = opts.signIn || "/q/auth/monday";',
  '  var FOLD_KEY = "tdot_om_fold";',
  '  function key(){ return (typeof peekKey === "function") ? peekKey() : getKey(); }',
  '  function rows(){ try { return (opts.rows && opts.rows()) || []; } catch (e) { return []; } }',
  '  function el(tag, cls, text){ var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; }',
  '  /* "2026-11-12 14:05" (Toronto) → "Thu, Nov 12, 14:05" — built from the parts, never a local Date */',
  '  function whenText(w){',
  '    w = String(w || "");',
  '    var d = w.slice(0, 10).split("-"), t = w.slice(11, 16);',
  '    if (d.length !== 3 || !Number(d[0]) || !Number(d[1]) || !Number(d[2])) return "";',
  '    var out = w.slice(0, 10);',
  '    try { out = new Intl.DateTimeFormat("en-CA", { timeZone: "UTC", weekday: "short", day: "numeric", month: "short", year: "numeric" }).format(new Date(Date.UTC(Number(d[0]), Number(d[1]) - 1, Number(d[2])))); } catch (e) {}',
  '    return out + (t ? ", " + t : "");',
  '  }',
  '  function optionText(c){',
  '    return (c.name || "No name") + " · " + (c.bookedSlot ? whenText(c.bookedSlot) : "no time booked") + (c.code ? " · " + c.code : "") + (c.consultant ? " · " + c.consultant : "");',
  '  }',
  '  /* keep = the list was emptied by what the person just did: the box stays, with the line that says what happened */',
  '  function count(keep){',
  '    nEl.textContent = "(" + ITEMS.length + ")";',
  '    strip.hidden = ITEMS.length === 0 && !keep;',
  '    if (hintEl) hintEl.hidden = ITEMS.length === 0;',
  '    if (doneEl) doneEl.hidden = ITEMS.length !== 0;',
  '  }',
  '  function setFold(open){',
  '    toggle.setAttribute("aria-expanded", open ? "true" : "false");',
  '    bodyEl.hidden = !open;',
  '    try { if (!window.TDOT_SIGNED_OUT) sessionStorage.setItem(FOLD_KEY, open ? "" : "1"); } catch (e) {}',
  '  }',
  '  toggle.onclick = function(){ setFold(toggle.getAttribute("aria-expanded") !== "true"); };',
  '  try { if (sessionStorage.getItem(FOLD_KEY) === "1") setFold(false); } catch (e) {}',
  '',
  '  /* the client picker: the suggestions, or — once something is typed — the consultations with that name or code */',
  '  function fill(sel, cands, q){',
  '    sel.innerHTML = "";',
  '    var seen = {};',
  '    function add(c){ var id = String(c.id); if (seen[id]) return; seen[id] = 1; var o = el("option", "", optionText(c)); o.value = id; sel.appendChild(o); }',
  '    function none(text){ var o = el("option", "", text); o.value = ""; sel.appendChild(o); }',
  '    q = String(q || "").trim().toLowerCase();',
  '    if (!q) {',
  '      if (!cands.length) none("Search for the client above");',
  '      for (var i = 0; i < cands.length; i++) add(cands[i]);',
  '      return;',
  '    }',
  '    var all = rows(), hits = 0;',
  '    for (var j = 0; j < all.length && hits < 30; j++) {',
  '      var c = all[j], code = String(c.recCode || "");',
  '      if (String(c.name || "").toLowerCase().indexOf(q) < 0 && code.toLowerCase().indexOf(q) < 0) continue;',
  '      if (seen[String(c.id)]) continue;',
  '      add({ id: c.id, name: c.name, bookedSlot: c.bookedSlot, consultant: c.consultant, code: code }); hits++;',
  '    }',
  '    if (!hits) none("No consultation with that name");',
  '  }',
  '',
  '  function send(id, what, payload){',
  '    return fetch("/api/otter/needs-matching/" + encodeURIComponent(id) + "/" + what, {',
  '      method: "POST", headers: { "X-Api-Key": key() || "", "Content-Type": "application/json" }, body: JSON.stringify(payload || {})',
  '    }).then(function(r){ return r.json().catch(function(){ return {}; }).then(function(j){ return { s: r.status, j: j }; }); });',
  '  }',
  '  function showErr(msg, res, fallback){',
  '    msg.className = "om-msg err"; msg.textContent = (res && res.j && res.j.error) || fallback;',
  '    if (res && res.s === 401 && res.j && res.j.loginUrl) {',
  '      msg.appendChild(document.createTextNode(" "));',
  '      var a = el("a", "", "Sign in with Monday"); a.href = SIGN_IN; msg.appendChild(a);',
  '    }',
  '  }',
  '  function gone(item, node, text){',
  '    var at = ITEMS.indexOf(item);',
  '    if (at >= 0) ITEMS.splice(at, 1);',
  '    if (node.parentNode) node.parentNode.removeChild(node);',
  '    topEl.textContent = text;',
  '    count(true);',
  '    if (ITEMS.length) { var next = listEl.querySelector("select, button"); if (next) next.focus(); }',
  '    else { if (bodyEl.hidden) setFold(true); try { toggle.focus(); } catch (e) {} }',
  '  }',
  '',
  '  function askNotConsult(onYes){',
  '    if (typeof tdotDialogNew !== "function") { if (window.confirm("Take this recording off the list? It is not deleted — an admin can bring it back.")) onYes(""); return; }',
  '    var dlg = tdotDialogNew({ cls: "tdlg-narrow", labelledBy: "om-dlg-title" });',
  '    var h = el("h3", "", "Not a consultation?"); h.id = "om-dlg-title";',
  '    var p = el("p", "", "The recording leaves this list. Nothing is deleted and nothing is added to any client. An admin can bring it back.");',
  '    var why = el("input", "om-why-box"); why.type = "text"; why.maxLength = 200; why.placeholder = "Why (optional) — for example: team meeting"; why.setAttribute("aria-label", "Why it is not a consultation (optional)");',
  '    var acts = el("div", "tdlg-actions");',
  '    var no = el("button", "tdlg-btn", "Cancel"); no.type = "button"; no.setAttribute("data-x", "");',
  '    var yes = el("button", "tdlg-btn primary", "Yes, take it off the list"); yes.type = "button";',
  '    acts.appendChild(no); acts.appendChild(yes);',
  '    dlg.box.appendChild(h); dlg.box.appendChild(p); dlg.box.appendChild(why); dlg.box.appendChild(acts);',
  '    no.onclick = function(){ dlg.tryClose("cancel"); };',
  '    yes.onclick = function(){ var v = why.value; dlg.close(true); onYes(v); };',
  '    setTimeout(function(){ try { no.focus(); } catch (e) {} }, 30);',
  '  }',
  '',
  '  function rowEl(item, i){',
  '    var node = el("div", "om-row"); node.setAttribute("role", "group");',
  '    var title = String(item.title || "").trim();',
  '    node.setAttribute("aria-label", "Recording " + (whenText(item.when) || "with no time") + (title ? ", " + title : ", no title"));',
  '    var left = el("div");',
  '    left.appendChild(el("div", "om-when", (whenText(item.when) || "Time not known") + (item.minutes ? " · about " + item.minutes + " min" : "")));',
  '    left.appendChild(el("div", "om-title" + (title ? "" : " none"), title || "No title"));',
  '    if (item.snippet) left.appendChild(el("p", "om-snip", item.snippet + (item.snippetCut ? "…" : "")));',
  '    else if (item.saveable === false) left.appendChild(el("p", "om-snip", "This recording file cannot be opened."));',
  '    else if (!item.fileRead) left.appendChild(el("p", "om-snip", "The recording could not be opened just now — refresh the page in a minute."));',
  '    left.appendChild(el("div", "om-why", item.reason || ""));',
  '    node.appendChild(left);',
  '',
  '    var pick = el("div", "om-pick");',
  '    var cands = item.candidates || [];',
  '    var sId = "om-s-" + i, cId = "om-c-" + i, mId = "om-m-" + i;',
  '    var sl = el("label", "", "Find the client"); sl.htmlFor = sId;',
  '    var search = el("input"); search.type = "search"; search.id = sId; search.autocomplete = "off"; search.placeholder = "Type a name or a code (TD-12345)";',
  '    var cl = el("label", "", cands.length ? "Client (suggested)" : "Client"); cl.htmlFor = cId;',
  '    var sel = el("select"); sel.id = cId; sel.setAttribute("aria-describedby", mId);',
  '    fill(sel, cands, "");',
  '    search.oninput = function(){ fill(sel, cands, search.value); cl.textContent = search.value.trim() ? "Client" : (cands.length ? "Client (suggested)" : "Client"); };',
  '    var acts = el("div", "om-acts");',
  '    var save = el("button", "om-btn primary", "Save to this client"); save.type = "button";',
  '    var not = el("button", "om-btn", "Not a consultation"); not.type = "button";',
  '    var msg = el("div", "om-msg"); msg.id = mId; msg.setAttribute("role", "status"); msg.setAttribute("aria-live", "polite");',
  '    /* a file that cannot be opened for good: only "Not a consultation" is offered — no picker, no Save */',
  '    var canSave = item.saveable !== false;',
  '    if (canSave) acts.appendChild(save);',
  '    acts.appendChild(not);',
  '    if (canSave) { pick.appendChild(sl); pick.appendChild(search); pick.appendChild(cl); pick.appendChild(sel); }',
  '    pick.appendChild(acts); pick.appendChild(msg);',
  '    node.appendChild(pick);',
  '',
  '    function busy(on, text){ save.disabled = on; not.disabled = on; sel.disabled = on; search.disabled = on; if (on) { msg.className = "om-msg"; msg.textContent = text; } }',
  '    save.onclick = function(){',
  '      var leadId = sel.value, label = sel.options[sel.selectedIndex] ? sel.options[sel.selectedIndex].textContent : "";',
  '      if (!leadId) { msg.className = "om-msg err"; msg.textContent = "Choose the client first."; search.focus(); return; }',
  '      busy(true, "Saving…");',
  '      send(item.otterId, "assign", { leadId: leadId })',
  '        .then(function(res){',
  '          if (res.s >= 400) { busy(false); showErr(msg, res, "It could not be saved (" + res.s + ")."); return; }',
  '          gone(item, node, "Saved to " + label.split(" · ")[0] + "." + (res.j.already ? " It was already on that client — nothing was added twice." : ""));',
  '        })',
  '        .catch(function(){ busy(false); msg.className = "om-msg err"; msg.textContent = "Network problem — it may not have been saved. Press Save again; it is never saved twice."; });',
  '    };',
  '    not.onclick = function(){',
  '      askNotConsult(function(why){',
  '        busy(true, "Taking it off the list…");',
  '        send(item.otterId, "dismiss", { why: why })',
  '          .then(function(res){',
  '            if (res.s >= 400) { busy(false); showErr(msg, res, "It could not be taken off the list (" + res.s + ")."); return; }',
  '            gone(item, node, "Taken off the list.");',
  '          })',
  '          .catch(function(){ busy(false); msg.className = "om-msg err"; msg.textContent = "Network problem — try again."; });',
  '      });',
  '    };',
  '    return node;',
  '  }',
  '',
  '  function load(){',
  '    var k = key(); if (!k) return;',
  '    fetch("/api/otter/needs-matching", { headers: { "X-Api-Key": k } })',
  '      .then(function(r){ return r.ok ? r.json() : null; })',
  '      .then(function(j){',
  '        if (!j || !j.on) { ITEMS = []; listEl.innerHTML = ""; topEl.textContent = ""; count(); return; }',
  '        ITEMS = (j.items || []).slice();',
  '        listEl.innerHTML = ""; topEl.textContent = "";',
  '        for (var i = 0; i < ITEMS.length; i++) listEl.appendChild(rowEl(ITEMS[i], i));',
  '        count();',
  '      })',
  '      .catch(function(){ /* the strip stays hidden: the Consultations list itself is not affected */ });',
  '  }',
  '  load();',
  '  window.tdotOtterMatchReload = load;',
  '}',
].join('\n');

module.exports = { OTTER_MATCH_CSS, otterMatchHtml, OTTER_MATCH_JS };
