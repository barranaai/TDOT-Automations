/**
 * The case page's "Emails" tab (Stage 2a, Faran 2026-11-19; switch CASE_EMAILS_TAB = off | admins | on).
 *
 *   CASE_EMAILS_CSS      — the list, the rows, the pop-up's body (.cem-*)
 *   caseEmailsTabButton  — the tab button (after Updates)
 *   caseEmailsHtml()     — the tab panel's STATIC markup: the page's render() / loadCase() never touch it
 *   CASE_EMAILS_JS       — defines window.tdotCaseEmailsMount({ caseRef, adminsOnly }): its own fetches of
 *                          /admin/case-emails/:caseRef (+ /message, /attachment), with the Monday cookie only
 *
 * Read-only (decision 1). Loads on the FIRST click of the tab; Refresh at most every 15 s. One status per source
 * ("Office mailbox ✓ · old no-reply inbox ✓"); a failed source says so with Retry, and "No emails yet" shows ONLY
 * when every source answered. One email opens in the shared pop-up (dialogUi.js tdotDialogNew): its plain text,
 * links as the server made them (secrets hidden; app links are text), the attachment list (downloaded with fetch +
 * a blob — never a ?key= link). Junk is folded until "Show" (decision 4).
 *
 * 'admins' mode: the page is built without knowing the viewer (critique #17), so the widget asks the route once
 * (?probe=1) and removes its own tab when the answer is 403 "admins-only".
 *
 * Rules kept here on purpose: every node is built with textContent / createTextNode — innerHTML is never used;
 * only http, https and mailto become links (target=_blank, rel=noopener noreferrer); the JS is a plain-string array
 * with no backticks, no backslashes and no dollar-brace (test/inlineScripts.test.js).
 */

