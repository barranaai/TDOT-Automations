function consultNotesHtml(prefix) {
  const p = String(prefix || 'cnw');
  return [
    `<p class="cnw-hint">Type here during or after the consultation. What you type is kept on this device as a draft until you press <b>Save notes</b>; then it is posted to this record’s Updates for the team. Until it is saved, anyone who uses this computer can see the draft. <b>Sign Out</b> removes drafts that were not saved (it asks first).</p>`,
    `<textarea id="${p}-text" class="cnw-text" placeholder="Type the consultation notes here…" aria-label="Consultation notes" aria-describedby="${p}-draft ${p}-count"></textarea>`,
    `<div class="cnw-under"><span id="${p}-draft" class="cnw-draft" aria-live="polite"></span><span id="${p}-count" class="cnw-count" aria-live="polite"></span></div>`,
    `<div class="cnw-row">`,
    `<input id="${p}-name" class="cnw-name" type="text" maxlength="60" placeholder="Your name" aria-label="Your name" title="Shown as [Name] on the saved notes">`,
    `<button class="btn primary" id="${p}-save" type="button">Save notes</button>`,
    `<span id="${p}-msg" class="cnw-msg" role="status"></span>`,
    `</div>`,
    `<div class="cnw-saved-t">Saved notes</div>`,
    `<div id="${p}-list" class="cnw-list"><div class="cnw-empty">Loading saved notes…</div></div>`,
  ].join('');
}

const CONSULT_NOTES_JS = [
  'function tdotConsultNotesMount(opts){',
  '  var p = opts.prefix || "cnw";',
  '  var el = function(id){ return document.getElementById(p + "-" + id); };',
  '  var ta = el("text"), saveBtn = el("save");',
  '  if (!ta || !saveBtn) return;',
  '  var itemId = String(opts.itemId || "");',
  '  var MAX = ' + MAX_CONSULT_NOTES + ', NEAR = ' + NEAR_LIMIT + ';',
  '  var NAME_KEY = "tdot_staff_name";',
  '  var DRAFT_KEY = "' + DRAFT_PREFIX + '" + itemId;',
  '  var NL = String.fromCharCode(10), CR = String.fromCharCode(13);',
  '  var saving = false;',
  '  var TAB = "t" + Date.now().toString(36) + Math.random().toString(36).slice(2, 8);   /* this open page */',
  '  var SO_KEY = "' + SIGNOUT_KEY + '", MAX_AGE = ' + (DRAFT_DAYS * 86400000) + ';',
  '  var SEP = NL + NL + "----------" + NL + NL;   /* between two drafts brought back together */',
  '  var adopted = {};      /* drafts of other tabs shown in this box: tab id → the text as it was brought back */',
  '  var restored = null;   /* the text brought back at load, while the box still shows exactly that */',
  '  var lastKept = "";     /* what this device holds for this box ("" nothing, null a failed write) */',
  '  var nameEl = el("name");',
  '',
  '  function num(n){ try { return Number(n).toLocaleString("en-CA"); } catch (e) { return String(n); } }',
  '  /* the text as it is counted and sent: line ends as one character, outer blanks dropped (the server counts the same) */',
  '  function clean(v){ return String(v == null ? "" : v).split(CR + NL).join(NL).split(CR).join(NL).trim(); }',
  '  function say(text, color){ var m = el("msg"); if (m) { m.textContent = text; m.style.color = color || "#64748b"; } }',
  '  /* today: the time; another day: the date too */',
  '  function whenOf(ms){',
  '    try {',
  '      var d = new Date(ms), t = d.toLocaleTimeString([], { hour: "numeric", minute: "2-digit" });',
  '      if (d.toDateString() === new Date().toDateString()) return t;',
  '      return d.toLocaleDateString([], { year: "numeric", month: "short", day: "numeric" }) + ", " + t;',
  '    } catch (e) { return ""; }',
  '  }',
  '  function draftLine(text, warn){ var d = el("draft"); if (d) { d.textContent = text; d.className = "cnw-draft" + (warn ? " warn" : ""); } }',
  '',
  '  /* Sign Out, here or in another tab of this browser, since this page opened */',
  '  function readMark(){ try { return localStorage.getItem(SO_KEY) || ""; } catch (e) { return ""; } }',
  '  var markAtLoad = readMark();',
  '  function signedOut(){ return !!window.TDOT_SIGNED_OUT || readMark() !== markAtLoad; }',
  '  var GONE = "Signed out — what is in the box is no longer kept on this device. Press Save notes to keep it.";',
  '',
  '  /* this record’s drafts on the device: tab id → { t, at, by }; null when the device cannot be read */',
  '  function readAll(){',
  '    try {',
  '      var raw = localStorage.getItem(DRAFT_KEY); if (!raw) return {};',
  '      var o = JSON.parse(raw), d = (o && o.d && typeof o.d === "object") ? o.d : {}, out = {};',
  '      for (var k in d) { if (d[k] && typeof d[k].t === "string" && d[k].t.trim()) out[k] = d[k]; }',
  '      return out;',
  '    } catch (e) { return null; }',
  '  }',
  '  /* throws when the device refuses */',
  '  function writeAll(d){',
  '    var any = false; for (var k in d) { any = true; break; }',
  '    if (!any) { localStorage.removeItem(DRAFT_KEY); return; }',
  '    var who = ""; var h = document.getElementById(opts.clientNameId || "c-name"); if (h) who = String(h.textContent || "").trim();',
  '    if (who.length < 2) who = "";',
  '    localStorage.setItem(DRAFT_KEY, JSON.stringify({ who: who.slice(0, 80), d: d }));',
  '  }',
  '  /* out with this tab’s draft and with the ones it brought back that nobody has changed since */',
  '  function withoutMine(d){',
  '    delete d[TAB];',
  '    for (var k in adopted) { if (d[k] && d[k].t === adopted[k]) delete d[k]; }',
  '    return d;',
  '  }',
  '  function dropDraft(){',
  '    try { var d = readAll(); if (d) writeAll(withoutMine(d)); } catch (e) {}',
  '    adopted = {}; restored = null; lastKept = "";',
  '  }',
  '  /* keeps what is in the box on this device; an empty box removes this tab’s draft. Never after Sign Out (shared computers). */',
  '  function keepDraft(){',
  '    var v = ta.value || "";',
  '    if (v !== restored) restored = null;',
  '    if (signedOut()) { lastKept = null; draftLine(v.trim() ? GONE : "", true); return; }',
  '    if (!v.trim()) { dropDraft(); draftLine(""); return; }',
  '    var at = Date.now();',
  '    try {',
  '      var d = withoutMine(readAll() || {});',
  '      d[TAB] = { t: v, at: at, by: ((nameEl && nameEl.value) || "").trim().slice(0, 60) };',
  '      writeAll(d); adopted = {}; lastKept = v;',
  '      draftLine("Draft kept on this device · " + whenOf(at));',
  '    } catch (e) { lastKept = null; draftLine("This device could not keep a draft — press Save notes before you leave this page.", true); }',
  '  }',
  '  /* is what is in the box on this device right now? (for the words after a save that did not go through) */',
  '  function keptWords(){',
  '    return (lastKept !== null && lastKept === (ta.value || "")) ? " Your draft is kept on this device."',
  '      : " Your draft is NOT kept on this device — copy the text somewhere safe before you leave this page.";',
  '  }',
  '  function count(){',
  '    var c = el("count"); if (!c) return;',
  '    var n = clean(ta.value).length;',
  '    if (n > MAX) { c.textContent = num(n) + " / " + num(MAX) + " — " + num(n - MAX) + " over the limit"; c.className = "cnw-count over"; }',
  '    else if (n >= MAX - NEAR) { c.textContent = num(n) + " / " + num(MAX) + " characters"; c.className = "cnw-count"; }',
  '    else { c.textContent = ""; c.className = "cnw-count"; }',
  '  }',
  '',
  '  /* shared computers: drafts nobody saved for ' + DRAFT_DAYS + ' days leave the device (every record, checked when a record opens) */',
  '  function sweepOld(){',
  '    try {',
  '      var now = Date.now(), keys = [];',
  '      for (var i = 0; i < localStorage.length; i++) { var k = localStorage.key(i); if (k && k.indexOf("' + DRAFT_PREFIX + '") === 0) keys.push(k); }',
  '      for (var j = 0; j < keys.length; j++) {',
  '        try {',
  '          var o = JSON.parse(localStorage.getItem(keys[j]) || "null"), d = (o && o.d && typeof o.d === "object") ? o.d : {}, left = 0;',
  '          for (var t in d) { if (d[t] && typeof d[t].t === "string" && d[t].t.trim() && now - Number(d[t].at) <= MAX_AGE) left++; else delete d[t]; }',
  '          if (!left) localStorage.removeItem(keys[j]); else { o.d = d; localStorage.setItem(keys[j], JSON.stringify(o)); }',
  '        } catch (e) { try { localStorage.removeItem(keys[j]); } catch (e2) {} }',
  '      }',
  '    } catch (e) {}',
  '  }',
  '',
  '  /* the name: the same remembered name as the Updates and Remarks boxes */',
  '  try { var savedName = localStorage.getItem(NAME_KEY); if (savedName && nameEl && !nameEl.value) nameEl.value = savedName; } catch (e) {}',
  '',
  '  /* bring kept drafts back — never over text already in the box. The line says when it was typed and by whom. */',
  '  function restore(){',
  '    if ((ta.value || "").trim() || signedOut()) return false;',
  '    var all = readAll(); if (!all) return false;',
  '    var list = []; for (var k in all) list.push({ k: k, t: all[k].t, at: Number(all[k].at) || 0, by: String(all[k].by || "") });',
  '    if (!list.length) return false;',
  '    list.sort(function(a, b){ return a.at - b.at; });',
  '    var texts = [], by = "", last = 0; adopted = {};',
  '    for (var i = 0; i < list.length; i++) { texts.push(list[i].t); if (list[i].k !== TAB) adopted[list[i].k] = list[i].t; if (list[i].by) by = list[i].by; if (list[i].at > last) last = list[i].at; }',
  '    ta.value = texts.join(SEP); restored = ta.value; lastKept = ta.value;',
  '    draftLine("Draft kept on this device · " + whenOf(last) + (by ? " · typed by " + by : "") + (list.length > 1 ? " · from " + list.length + " tabs" : "") + " — not saved yet");',
  '    return true;',
  '  }',
  '  sweepOld();',
  '  restore();',
  '  count();',
  '',
  '  ta.addEventListener("input", function(){ keepDraft(); count(); if (!saving) say(""); });',
  '',
  '  /* Sign Out asks about text that is in a box but could not be kept on the device */',
  '  window.tdotNotesUnsaved = function(){ return !!clean(ta.value); };',
  '',
  '  /* another tab of this browser: Sign Out there, or this record’s draft saved / changed / removed there */',
  '  window.addEventListener("storage", function(ev){',
  '    if (!ev) return;',
  '    if (ev.key === SO_KEY) { if ((ta.value || "").trim()) { lastKept = null; draftLine(GONE, true); } return; }',
  '    if (ev.key !== DRAFT_KEY && ev.key !== null) return;',
  '    /* a box that still shows a brought-back draft untouched follows the device, so there is one copy, not two */',
  '    if (restored === null || saving || (ta.value || "") !== restored) return;',
  '    var all = readAll(); if (!all) return;',
  '    var same = false, any = false;',
  '    for (var k in adopted) { any = true; if (all[k] && all[k].t === adopted[k]) { same = true; } else { same = false; break; } }',
  '    if (any && same) return;',
  '    ta.value = ""; adopted = {}; restored = null; lastKept = "";',
  '    if (!restore()) draftLine("This draft was saved or removed in another tab.");',
  '    count();',
  '  });',
  '',
  '  /* leaving with unsaved text asks first (the browser shows its own words); the draft is kept either way.',
  '     Not after Sign Out: it asked already, and the drafts are gone on purpose. */',
  '  window.addEventListener("beforeunload", function(ev){',
  '    if (window.TDOT_SIGNED_OUT) return;',
  '    if (!clean(ta.value)) return;',
  '    if ((ta.value || "") !== lastKept) keepDraft();',
  '    ev.preventDefault(); ev.returnValue = "";',
  '    return "";',
  '  });',
  '',
  '  function renderList(notes){',
  '    var list = el("list"); if (!list) return; list.innerHTML = "";',
  '    if (!notes.length) { var e = document.createElement("div"); e.className = "cnw-empty"; e.textContent = "No consultation notes saved yet."; list.appendChild(e); return; }',
  '    for (var i = 0; i < notes.length; i++) {',
  '      var n = notes[i];',
  '      var item = document.createElement("div"); item.className = "cnw-item";',
  '      var head = document.createElement("div"); head.className = "cnw-head";',
  '      var by = document.createElement("span"); by.className = "cnw-by"; by.textContent = n.by || "Name not given"; head.appendChild(by);',
  '      if (n.updated) { var tag = document.createElement("span"); tag.className = "cnw-tag"; tag.textContent = "Updated"; head.appendChild(tag); }',
  '      var at = document.createElement("span"); var dt = new Date(n.at);',
  '      at.textContent = isNaN(dt.getTime()) ? String(n.at || "") : dt.toLocaleString([], { year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" });',
  '      head.appendChild(at);',
  '      item.appendChild(head);',
  '      var body = document.createElement("div"); body.className = "cnw-body"; body.textContent = n.body; item.appendChild(body);',
  '      list.appendChild(item);',
  '    }',
  '  }',
  '  function listNote(text){ var list = el("list"); if (!list) return; list.innerHTML = ""; var e = document.createElement("div"); e.className = "cnw-empty"; e.textContent = text; list.appendChild(e); }',
  '  function loadList(){',
  '    var key = (typeof peekKey === "function") ? peekKey() : getKey();',
  '    if (!key) { listNote("Saved notes need the admin key (enter it on the sign-in page)."); return; }',
  '    fetch("/api/updates/" + encodeURIComponent(itemId) + "?kind=consultNotes", { headers: { "X-Api-Key": key } })',
  '      .then(function(r){ return r.json(); })',
  '      .then(function(j){ if (j.error) { listNote(j.error); return; } renderList(j.notes || []); })',
  '      .catch(function(){ listNote("Could not load the saved notes — refresh to retry."); });',
  '  }',
  '',
  '  saveBtn.onclick = function(){',
  '    if (saving) return;',
  '    var sentRaw = ta.value || "";',
  '    var text = clean(sentRaw);',
  '    var name = ((nameEl && nameEl.value) || "").trim();',
  '    if (!text) { say("Type the consultation notes first.", "#c0392b"); ta.focus(); return; }',
  '    if (text.length > MAX) { say("Consultation notes are limited to " + num(MAX) + " characters — this is " + num(text.length - MAX) + " over. Nothing was saved. Shorten the notes, or save them in two parts.", "#c0392b"); count(); return; }',
  '    if (!name) { say("Add your name so the team knows who wrote the notes.", "#c0392b"); if (nameEl) nameEl.focus(); return; }',
  '    if (!itemId) { say("No record to save to.", "#c0392b"); return; }',
  '    if ((ta.value || "") !== lastKept) keepDraft();   /* before anything that can leave the page */',
  '    try { localStorage.setItem(NAME_KEY, name); } catch (e) {}',
  '    var other = document.getElementById((opts.updatesPrefix || "updw") + "-name"); if (other && !other.value) other.value = name;',
  '    var key = (typeof peekKey === "function") ? peekKey() : getKey();',
  '    if (!key) { say("Saving needs the admin key (enter it on the sign-in page)." + keptWords(), "#c0392b"); return; }',
  '    saving = true; saveBtn.disabled = true; say("Saving…");',
  '    fetch("/api/updates/" + encodeURIComponent(itemId), {',
  '      method: "POST", headers: { "X-Api-Key": key, "Content-Type": "application/json" },',
  '      body: JSON.stringify({ body: text, staffName: name, kind: "consultNotes" }),',
  '    })',
  '      .then(function(r){ return r.json().then(function(j){ return { s: r.status, j: j || {} }; }, function(){ return { s: r.status, j: {} }; }); })',
  '      .then(function(res){',
  '        if (res.s < 200 || res.s >= 300) {',
  '          say((res.j.error || ("Could not save (error " + res.s + ").")) + keptWords(), "#c0392b");',
  '          return;',
  '        }',
  '        var done = res.j.already ? "These notes were already saved — no second copy was made." : (res.j.updated ? "Saved as Consultation notes (updated)." : "Consultation notes saved.");',
  '        if ((ta.value || "") === sentRaw) { ta.value = ""; dropDraft(); draftLine(""); say(done, "#16a34a"); }',
  '        else { keepDraft(); say(done + " What you typed after pressing Save is still in the box as a draft.", "#16a34a"); }',
  '        count();',
  '        loadList();',
  '        var reload = window["tdotUpdatesReload_" + (opts.updatesPrefix || "updw")]; if (typeof reload === "function") reload();',
  '      })',
  '      .catch(function(){ say("Could not reach the server, so the notes may not be saved." + keptWords() + " Press Save notes again (it will not make a second copy).", "#c0392b"); })',
  '      .finally(function(){ saving = false; saveBtn.disabled = false; });',
  '  };',
  '',
  '  loadList();',
  '}',
].join('\n');

