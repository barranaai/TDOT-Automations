/**
 * Consultation notes box — on the consultation record page (2026-11-10).
 *
 * The consultant types during or after the call. The DRAFT is kept in this browser as they
 * type (per record; never sent anywhere until "Save notes"); "Save notes" posts the text as
 * ONE labelled update on the lead ("📝 Consultation notes" / "(updated)"), through the same
 * server path as the Otter summary (POST /api/updates/:itemId, kind "consultNotes").
 *
 *   CONSULT_NOTES_CSS          — styles (namespaced .cnw-*)
 *   consultNotesHtml(prefix)   — the card body (STATIC markup: the page's render() never rewrites it)
 *   CONSULT_NOTES_JS           — defines window.tdotConsultNotesMount(opts)
 *
 * Rules kept here on purpose:
 *   - no maxlength on the box: a long paste is never cut; over the limit is REFUSED with a message;
 *   - every storage call is in try/catch; the box works without storage;
 *   - the draft is cleared only after the server said yes, and only if the box still holds what was sent;
 *   - one storage key per record holds a draft PER TAB ({ who, d: { tab: { t, at, by } } }): a tab writes and removes
 *     only its own draft (plus the ones it brought back into its box), so the record open twice never loses text;
 *   - a tab writes on leaving only what it has not already kept (a stale tab never puts a saved draft back);
 *   - Sign Out (adminShared.js) asks before it removes drafts and stamps SIGNOUT_KEY; after that — in this tab or
 *     any other — nothing more is kept, and no message may say "your draft is kept";
 *   - drafts older than DRAFT_DAYS are removed when a record page opens (shared computers);
 *   - saved entries are rendered with textContent, never innerHTML;
 *   - the JS is a plain-string array with no backticks and no backslash escapes (see test/inlineScripts.test.js).
 */

